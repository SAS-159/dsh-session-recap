/**
 * Build src/ into the two artifacts DSH loads.
 *
 *   dist/index.js    Host half, ESM
 *   dist/client.js   browser half, CJS wrapped in __ModuleLoader__.load
 *
 * React and react-dom stay external: the page's module table provides them
 * through the factory's `require`. The loader keys factories by package name,
 * so the registration id is read from package.json, never hard-coded.
 */
import { build } from 'esbuild'
import { access, mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const pkg = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'))
const kit = pkg.kit ?? {}
const id = pkg.name

async function exists(path) {
  try {
    await access(path)
    return true
  } catch {
    return false
  }
}

const clientEntry = join(root, kit.entry?.client ?? 'src/client.tsx')
const hostEntry = join(root, kit.entry?.host ?? 'src/host.ts')
for (const entry of [clientEntry, hostEntry]) {
  if (!(await exists(entry))) throw new Error(`entry not found: ${entry}`)
}

await mkdir(join(root, 'dist'), { recursive: true })

const client = await build({
  entryPoints: [clientEntry],
  bundle: true,
  write: false,
  format: 'cjs',
  platform: 'browser',
  target: ['es2020'],
  jsx: 'automatic',
  external: ['react', 'react-dom', 'react/jsx-runtime'],
  loader: { '.css': 'text' },
  legalComments: 'none',
  logLevel: 'silent',
})

const body = client.outputFiles[0].text
const wrapped = [
  '/* generated by scripts/build.mjs — edit src/, not this file */',
  'window.__ModuleLoader__.load({',
  `  id: ${JSON.stringify(id)},`,
  '  factory(require) {',
  '    var module = { exports: {} };',
  '    var exports = module.exports;',
  body,
  '    return module.exports;',
  '  },',
  '});',
  '',
].join('\n')

await writeFile(join(root, 'dist', 'client.js'), wrapped, 'utf8')

const host = await build({
  entryPoints: [hostEntry],
  bundle: true,
  write: false,
  format: 'esm',
  platform: 'node',
  target: ['node20'],
  packages: 'external',
  legalComments: 'none',
  logLevel: 'silent',
})

await writeFile(join(root, 'dist', 'index.js'), host.outputFiles[0].text, 'utf8')

console.log(`built ${id}`)
console.log(`  dist/client.js  ${Buffer.byteLength(wrapped)} bytes`)
console.log(`  dist/index.js   ${Buffer.byteLength(host.outputFiles[0].text)} bytes`)
